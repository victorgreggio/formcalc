use crate::error::{CalculatorError, Result};
use crate::formula::{Formula, FormulaT};
use crate::function::{build_function_id, Function};
use crate::graph::DAGraph;
use crate::parser::{Evaluator, Expr, Parser, Program, Statement};
use crate::trace::{ExecutionTrace, FormulaTrace, TraceOptions, TraceStep};
use crate::value::Value;
use rayon::prelude::*;
use std::collections::HashMap;
use std::sync::Arc;

#[derive(Debug, Clone)]
struct CompiledFormula {
    body: String,
    program: Program,
    dependencies: Vec<String>,
}

struct FormulaExecution {
    result: Result<Value>,
    steps: Vec<TraceStep>,
    truncated: bool,
}

/// Main engine for parsing and executing formulas with dependency resolution.
///
/// The `Engine` manages variables, functions, formula results, and automatically
/// resolves dependencies between formulas to execute them in the correct order.
/// Formulas in the same dependency layer are executed in parallel for optimal performance.
///
/// # Examples
///
/// ```
/// use formcalc::{Engine, Formula, Value};
/// use rust_decimal::Decimal;
///
/// let mut engine = Engine::new();
/// engine.set_variable("x".to_string(), Value::Number(Decimal::new(10, 0)));
///
/// let formula = Formula::new("doubled", "return x * 2");
/// engine.execute(vec![formula]).unwrap();
///
/// let result = engine.get_result("doubled").unwrap();
/// assert_eq!(result, Value::Number(Decimal::new(20, 0)));
/// ```
pub struct Engine {
    variable_cache: VariableCache,
    formula_result_cache: FormulaResultCache,
    function_cache: FunctionCache,
    errors: HashMap<String, String>,
    compiled_formulas: HashMap<String, CompiledFormula>,
    trace_options: Option<TraceOptions>,
    last_trace: ExecutionTrace,
}

impl Engine {
    /// Creates a new `Engine` instance with empty caches.
    ///
    /// # Examples
    ///
    /// ```
    /// use formcalc::Engine;
    ///
    /// let engine = Engine::new();
    /// ```
    pub fn new() -> Self {
        Self {
            variable_cache: VariableCache::new(),
            formula_result_cache: FormulaResultCache::new(),
            function_cache: FunctionCache::new(),
            errors: HashMap::new(),
            compiled_formulas: HashMap::new(),
            trace_options: None,
            last_trace: ExecutionTrace::default(),
        }
    }

    /// Sets a variable that can be referenced in formulas.
    ///
    /// Variables can be used directly in formula expressions by name.
    ///
    /// # Arguments
    ///
    /// * `name` - The variable name
    /// * `value` - The value to assign to the variable
    ///
    /// # Examples
    ///
    /// ```
    /// use formcalc::{Engine, Value};
    /// use rust_decimal::Decimal;
    ///
    /// let mut engine = Engine::new();
    /// engine.set_variable("pi".to_string(), Value::Number(Decimal::new(314_159, 5)));
    /// ```
    pub fn set_variable(&mut self, name: String, value: Value) {
        self.variable_cache.set(name, value);
    }

    /// Registers a custom function that can be called from formulas.
    ///
    /// Functions are identified by their name and number of arguments.
    /// You can register multiple functions with the same name but different arities.
    ///
    /// # Arguments
    ///
    /// * `function` - An `Arc` containing a type implementing the [`Function`] trait
    ///
    /// # Examples
    ///
    /// ```
    /// use formcalc::{Engine, Function, Value, Result, CalculatorError};
    /// use std::sync::Arc;
    ///
    /// struct SquareFunction;
    ///
    /// impl Function for SquareFunction {
    ///     fn name(&self) -> &str { "square" }
    ///     fn num_args(&self) -> usize { 1 }
    ///     fn execute(&self, params: &[Value]) -> Result<Value> {
    ///         match params[0] {
    ///             Value::Number(n) => Ok(Value::Number(n * n)),
    ///             _ => Err(CalculatorError::TypeError("Expected number".to_string())),
    ///         }
    ///     }
    /// }
    ///
    /// let mut engine = Engine::new();
    /// engine.register_function(Arc::new(SquareFunction));
    /// ```
    pub fn register_function(&mut self, function: Arc<dyn Function>) {
        let function_id = build_function_id(function.name(), function.num_args());
        self.function_cache.set(function_id, function);
    }

    /// Enables bounded expression tracing for subsequent executions.
    pub fn enable_tracing(&mut self, options: TraceOptions) {
        self.trace_options = Some(options);
    }

    /// Disables tracing and releases the most recently retained trace.
    pub fn disable_tracing(&mut self) {
        self.trace_options = None;
        self.last_trace = ExecutionTrace::default();
    }

    /// Returns the trace generated by the most recent traced execution.
    pub fn get_trace(&self) -> &ExecutionTrace {
        &self.last_trace
    }

    /// Executes multiple formulas with automatic dependency resolution.
    ///
    /// The engine analyzes dependencies between formulas (via `get_output_from` calls),
    /// builds a dependency graph, and executes formulas in topological order.
    /// Formulas in the same dependency layer are executed in parallel for performance.
    ///
    /// # Arguments
    ///
    /// * `formulas` - A vector of [`Formula`] instances to execute
    ///
    /// # Returns
    ///
    /// Returns `Ok(())` if dependency resolution succeeds, or an error if there are
    /// circular dependencies or invalid graph structures.
    ///
    /// Individual formula execution errors are captured and available via [`Engine::get_errors`].
    ///
    /// # Examples
    ///
    /// ```
    /// use formcalc::{Engine, Formula, Value};
    /// use rust_decimal::Decimal;
    ///
    /// let mut engine = Engine::new();
    ///
    /// let f1 = Formula::new("a", "return 10");
    /// let f2 = Formula::new("b", "return get_output_from('a') * 2");
    /// let f3 = Formula::new("c", "return get_output_from('b') + 5");
    ///
    /// engine.execute(vec![f1, f2, f3]).unwrap();
    ///
    /// assert_eq!(engine.get_result("c"), Some(Value::Number(Decimal::new(25, 0))));
    /// ```
    pub fn execute(&mut self, formulas: Vec<Formula>) -> Result<()> {
        self.formula_result_cache.clear();
        self.errors.clear();
        self.last_trace = ExecutionTrace::default();

        let mut graph = DAGraph::new();

        for formula in &formulas {
            let compiled = self.compile_formula(formula)?;
            graph
                .add_node(
                    formula.name().to_string(),
                    compiled.clone(),
                    compiled.dependencies.clone(),
                )
                .map_err(CalculatorError::DependencyError)?;
        }

        // Topological sort to get execution order
        let (layers, detached) = graph.topological_sort();

        // Handle detached (unresolvable) formulas
        for formula_name in detached {
            let error_msg = format!(
                "Could not resolve dependency path for formula: '{}'",
                formula_name
            );
            self.errors.insert(formula_name, error_msg);
        }

        // Execute formulas layer by layer
        // Formulas in the same layer can be executed in parallel
        for layer in layers {
            self.execute_layer_parallel(&graph, layer);
        }

        self.last_trace
            .formulas
            .sort_by(|left, right| left.formula_name.cmp(&right.formula_name));
        Ok(())
    }

    /// Execute all formulas in a layer in parallel
    fn execute_layer_parallel(
        &mut self,
        graph: &DAGraph<String, CompiledFormula>,
        layer: Vec<String>,
    ) {
        // Execute formulas in parallel
        let results: Vec<(String, FormulaExecution)> = layer
            .par_iter()
            .filter_map(|formula_name| {
                graph.get(formula_name).map(|formula| {
                    let result = self.try_execute_formula(formula);
                    (formula_name.clone(), result)
                })
            })
            .collect();

        // Process results sequentially to update caches and collect errors
        for (formula_name, execution) in results {
            let dependencies = graph
                .get(&formula_name)
                .expect("graph formula exists")
                .dependencies
                .clone();
            let traced_result = execution.result.clone().map_err(|error| error.to_string());

            match execution.result {
                Ok(value) => {
                    self.formula_result_cache.set(formula_name.clone(), value);
                }
                Err(e) => {
                    let error_msg = format!("Error executing formula '{}': {}", formula_name, e);
                    self.errors.insert(formula_name.clone(), error_msg);
                }
            }

            if self.trace_options.is_some() {
                self.last_trace.formulas.push(FormulaTrace {
                    formula_name,
                    dependencies,
                    result: traced_result,
                    steps: execution.steps,
                    truncated: execution.truncated,
                });
            }
        }
    }

    fn try_execute_formula(&self, formula: &CompiledFormula) -> FormulaExecution {
        let evaluator = Evaluator::new(
            self.variable_cache.clone(),
            self.formula_result_cache.clone(),
            self.function_cache.clone(),
        );

        if let Some(options) = self.trace_options {
            let (result, steps, truncated) =
                evaluator.evaluate_with_trace(&formula.program, options.max_steps_per_formula);
            FormulaExecution {
                result,
                steps,
                truncated,
            }
        } else {
            FormulaExecution {
                result: evaluator.evaluate(&formula.program),
                steps: Vec::new(),
                truncated: false,
            }
        }
    }

    fn compile_formula(&mut self, formula: &Formula) -> Result<&CompiledFormula> {
        let needs_compile = self
            .compiled_formulas
            .get(formula.name())
            .is_none_or(|compiled| compiled.body != formula.body());

        if needs_compile {
            let mut parser = Parser::new(formula.body())?;
            let program = parser.parse()?;
            let dependencies = collect_dependencies(&program)?;

            self.compiled_formulas.insert(
                formula.name().to_string(),
                CompiledFormula {
                    body: formula.body().to_string(),
                    program,
                    dependencies,
                },
            );
        }

        Ok(self
            .compiled_formulas
            .get(formula.name())
            .expect("compiled formula was inserted"))
    }

    /// Retrieves the result of a previously executed formula.
    ///
    /// # Arguments
    ///
    /// * `formula_name` - The name of the formula whose result to retrieve
    ///
    /// # Returns
    ///
    /// Returns `Some(Value)` if the formula executed successfully, or `None` if the
    /// formula hasn't been executed or failed with an error.
    ///
    /// # Examples
    ///
    /// ```
    /// use formcalc::{Engine, Formula, Value};
    /// use rust_decimal::Decimal;
    ///
    /// let mut engine = Engine::new();
    /// let formula = Formula::new("test", "return 42");
    /// engine.execute(vec![formula]).unwrap();
    ///
    /// assert_eq!(engine.get_result("test"), Some(Value::Number(Decimal::new(42, 0))));
    /// assert_eq!(engine.get_result("nonexistent"), None);
    /// ```
    pub fn get_result(&self, formula_name: &str) -> Option<Value> {
        self.formula_result_cache.get(formula_name)
    }

    /// Returns a map of all errors that occurred during the last execution.
    ///
    /// The map keys are formula names and values are error messages.
    ///
    /// # Examples
    ///
    /// ```
    /// use formcalc::{Engine, Formula};
    ///
    /// let mut engine = Engine::new();
    /// let formula = Formula::new("bad", "return 1 / 0");
    /// engine.execute(vec![formula]).unwrap();
    ///
    /// assert!(!engine.get_errors().is_empty());
    /// ```
    pub fn get_errors(&self) -> &HashMap<String, String> {
        &self.errors
    }

    /// Clears all variables, formula results, and errors.
    ///
    /// Note: Registered custom functions are preserved.
    ///
    /// # Examples
    ///
    /// ```
    /// use formcalc::{Engine, Formula, Value};
    /// use rust_decimal::Decimal;
    ///
    /// let mut engine = Engine::new();
    /// engine.set_variable("x".to_string(), Value::Number(Decimal::new(10, 0)));
    /// let formula = Formula::new("test", "return x");
    /// engine.execute(vec![formula]).unwrap();
    ///
    /// engine.clear();
    ///
    /// assert_eq!(engine.get_result("test"), None);
    /// ```
    pub fn clear(&mut self) {
        self.variable_cache.clear();
        self.formula_result_cache.clear();
        self.errors.clear();
    }
}

fn collect_dependencies(program: &Program) -> Result<Vec<String>> {
    let mut dependencies = Vec::new();
    collect_statement_dependencies(&program.statement, &mut dependencies)?;
    dependencies.sort();
    dependencies.dedup();
    Ok(dependencies)
}

fn collect_statement_dependencies(
    statement: &Statement,
    dependencies: &mut Vec<String>,
) -> Result<()> {
    match statement {
        Statement::Return(expr) | Statement::Error(expr) => {
            collect_expression_dependencies(expr, dependencies)
        }
        Statement::If {
            condition,
            then_block,
            else_ifs,
            else_block,
        } => {
            collect_expression_dependencies(condition, dependencies)?;
            collect_statement_dependencies(then_block, dependencies)?;
            for (condition, block) in else_ifs {
                collect_expression_dependencies(condition, dependencies)?;
                collect_statement_dependencies(block, dependencies)?;
            }
            if let Some(block) = else_block {
                collect_statement_dependencies(block, dependencies)?;
            }
            Ok(())
        }
    }
}

fn collect_expression_dependencies(expr: &Expr, dependencies: &mut Vec<String>) -> Result<()> {
    match expr {
        Expr::GetOutputFrom(argument) => match argument.as_ref() {
            Expr::String(name) => {
                dependencies.push(name.clone());
                Ok(())
            }
            _ => Err(CalculatorError::DependencyError(
                "get_output_from requires a string literal in deterministic mode".to_string(),
            )),
        },
        Expr::FunctionCall { args, .. } => {
            for argument in args {
                collect_expression_dependencies(argument, dependencies)?;
            }
            Ok(())
        }
        Expr::Not(expr)
        | Expr::UnaryMinus(expr)
        | Expr::Ceil(expr)
        | Expr::Floor(expr)
        | Expr::Exp(expr)
        | Expr::Year(expr)
        | Expr::Month(expr)
        | Expr::Day(expr) => collect_expression_dependencies(expr, dependencies),
        Expr::Substr(first, second, third) => {
            collect_expression_dependencies(first, dependencies)?;
            collect_expression_dependencies(second, dependencies)?;
            collect_expression_dependencies(third, dependencies)
        }
        Expr::Add(left, right)
        | Expr::Subtract(left, right)
        | Expr::Multiply(left, right)
        | Expr::Divide(left, right)
        | Expr::Power(left, right)
        | Expr::Modulo(left, right)
        | Expr::Equal(left, right)
        | Expr::NotEqual(left, right)
        | Expr::LessThan(left, right)
        | Expr::GreaterThan(left, right)
        | Expr::LessThanOrEqual(left, right)
        | Expr::GreaterThanOrEqual(left, right)
        | Expr::And(left, right)
        | Expr::Or(left, right)
        | Expr::Max(left, right)
        | Expr::Min(left, right)
        | Expr::Rnd(left, right)
        | Expr::AddDays(left, right)
        | Expr::GetDiffDays(left, right)
        | Expr::PaddedString(left, right)
        | Expr::GetDiffMonths(left, right) => {
            collect_expression_dependencies(left, dependencies)?;
            collect_expression_dependencies(right, dependencies)
        }
        Expr::Number(_) | Expr::String(_) | Expr::Bool(_) | Expr::Identifier(_) => Ok(()),
    }
}

