#[cfg(test)]
mod tests {
    use super::*;
    use rust_decimal::Decimal;

    fn number(value: i64) -> Value {
        Value::Number(Decimal::new(value, 0))
    }

    struct AddFunction;

    impl Function for AddFunction {
        fn name(&self) -> &str {
            "add"
        }

        fn num_args(&self) -> usize {
            2
        }

        fn execute(&self, params: &[Value]) -> Result<Value> {
            match params {
                [Value::Number(left), Value::Number(right)] => {
                    Ok(Value::Number(left.checked_add(*right).unwrap()))
                }
                _ => Err(CalculatorError::TypeError(
                    "Add requires two numbers".to_string(),
                )),
            }
        }
    }

    #[test]
    fn test_simple_formula() {
        let mut engine = Engine::new();
        let formula = Formula::new("test", "return 2 + 2");

        engine.execute(vec![formula]).unwrap();

        let result = engine.get_result("test").unwrap();
        assert_eq!(result, number(4));
    }

    #[test]
    fn test_formula_with_variable() {
        let mut engine = Engine::new();
        engine.set_variable("x".to_string(), number(10));

        let formula = Formula::new("test", "return x * 2");
        engine.execute(vec![formula]).unwrap();

        let result = engine.get_result("test").unwrap();
        assert_eq!(result, number(20));
    }

    #[test]
    fn test_formula_dependencies() {
        let mut engine = Engine::new();

        let formula1 = Formula::new("first", "return 10");
        let formula2 = Formula::new("second", "return get_output_from('first') * 2");

        engine.execute(vec![formula1, formula2]).unwrap();

        // Check for errors
        if !engine.get_errors().is_empty() {
            for (name, error) in engine.get_errors() {
                eprintln!("Error in {}: {}", name, error);
            }
        }

        let result = engine
            .get_result("second")
            .expect("second formula should have result");
        assert_eq!(result, number(20));
    }

    #[test]
    fn test_if_statement() {
        let mut engine = Engine::new();
        let formula = Formula::new("test", "if (5 > 3) then return 100 else return 200 end");

        engine.execute(vec![formula]).unwrap();

        let result = engine.get_result("test").unwrap();
        assert_eq!(result, number(100));
    }

    #[test]
    fn test_parallel_execution() {
        let mut engine = Engine::new();

        // Create multiple independent formulas that can be executed in parallel
        let formulas = vec![
            Formula::new("a", "return 1 + 1"),
            Formula::new("b", "return 2 + 2"),
            Formula::new("c", "return 3 + 3"),
            Formula::new("d", "return 4 + 4"),
            Formula::new("e", "return 5 + 5"),
        ];

        engine.execute(formulas).unwrap();

        assert_eq!(engine.get_result("a").unwrap(), number(2));
        assert_eq!(engine.get_result("b").unwrap(), number(4));
        assert_eq!(engine.get_result("c").unwrap(), number(6));
        assert_eq!(engine.get_result("d").unwrap(), number(8));
        assert_eq!(engine.get_result("e").unwrap(), number(10));
    }

    #[test]
    fn test_parallel_with_dependencies() {
        let mut engine = Engine::new();

        // Layer 0: a, b (can execute in parallel)
        // Layer 1: c, d (can execute in parallel, both depend on layer 0)
        // Layer 2: e (depends on layer 1)
        let formulas = vec![
            Formula::new("a", "return 10"),
            Formula::new("b", "return 20"),
            Formula::new("c", "return get_output_from('a') * 2"),
            Formula::new("d", "return get_output_from('b') * 2"),
            Formula::new("e", "return get_output_from('c') + get_output_from('d')"),
        ];

        engine.execute(formulas).unwrap();

        assert_eq!(engine.get_result("a").unwrap(), number(10));
        assert_eq!(engine.get_result("b").unwrap(), number(20));
        assert_eq!(engine.get_result("c").unwrap(), number(20));
        assert_eq!(engine.get_result("d").unwrap(), number(40));
        assert_eq!(engine.get_result("e").unwrap(), number(60));
    }

    #[test]
    fn test_dependencies_are_extracted_from_parsed_formula() {
        let mut engine = Engine::new();
        engine
            .execute(vec![
                Formula::new("first", "return 10"),
                Formula::new("second", "return get_output_from( 'first' ) * 2"),
            ])
            .unwrap();

        assert_eq!(engine.get_result("second"), Some(number(20)));
    }

    #[test]
    fn test_dynamic_dependencies_are_rejected() {
        let mut engine = Engine::new();
        engine.set_variable("source".to_string(), Value::from("first"));

        let error = engine
            .execute(vec![Formula::new(
                "second",
                "return get_output_from(source)",
            )])
            .unwrap_err();

        assert!(matches!(error, CalculatorError::DependencyError(_)));
    }

    #[test]
    fn test_custom_function_results_are_not_cached_by_arity() {
        let mut engine = Engine::new();
        engine.register_function(Arc::new(AddFunction));
        engine
            .execute(vec![Formula::new(
                "result",
                "return add(1, 2) + add(10, 20)",
            )])
            .unwrap();

        assert_eq!(engine.get_result("result"), Some(number(33)));
    }

    #[test]
    fn test_trace_is_bounded_and_contains_intermediate_results() {
        let mut engine = Engine::new();
        engine.enable_tracing(TraceOptions {
            max_steps_per_formula: 2,
        });
        engine
            .execute(vec![Formula::new("result", "return 1 + 2")])
            .unwrap();

        let trace = engine.get_trace();
        assert_eq!(trace.formulas.len(), 1);
        assert_eq!(trace.formulas[0].formula_name, "result");
        assert_eq!(trace.formulas[0].steps.len(), 2);
        assert!(trace.formulas[0].truncated);
        assert_eq!(trace.formulas[0].steps[0].result, number(1));
        assert_eq!(trace.formulas[0].steps[1].result, number(2));
    }
}
